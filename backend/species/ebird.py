"""eBird species codes, for the species page's eBird and All About Birds links.

Both sites key their pages on eBird's code ("blujay"), not on a name.
``ebird_codes.csv`` maps every taxonomy species to its code and is generated by
``scripts/build_ebird_codes.py``. The code is looked up at response time, so a
species row needs no column and existing rows get links without a backfill.
"""

import csv
from functools import cache
from pathlib import Path

_CSV = Path(__file__).with_name("ebird_codes.csv")


@cache
def _tables() -> tuple[dict[str, str], dict[str, str]]:
    by_sci, by_common = {}, {}
    with open(_CSV, newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            by_sci[row["scientific_name"].lower()] = row["ebird_code"]
            by_common[row["common_name"].lower()] = row["ebird_code"]
    return by_sci, by_common


def ebird_code(common_name: str, genus: str, species_name: str) -> str | None:
    """The eBird code for a species, or None for one outside the taxonomy.

    Scientific name first. Common name catches a Tier 3 answer that uses a
    newer genus than the taxonomy ("Astur cooperii" for Cooper's Hawk).
    """
    by_sci, by_common = _tables()
    return (
        by_sci.get(f"{genus} {species_name}".strip().lower())
        or by_common.get(common_name.strip().lower())
    )
